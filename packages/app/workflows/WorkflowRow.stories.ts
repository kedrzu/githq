import type { Meta, StoryObj } from '@storybook/vue3-vite';
import { defineComponent, h } from 'vue';

import { SAMPLE_WORKFLOWS, SAMPLE_WORKFLOWS_NOW } from '@/testing/sampleWorkflows.js';

import WorkflowRow from './WorkflowRow.vue';
import type { WorkflowRowRef } from './WorkflowTypes.js';

const MAIN: WorkflowRowRef = { name: 'main', kind: 'branch' };
const TAGS: WorkflowRowRef = { name: 'v*', kind: 'tag' };

const meta = {
    component: WorkflowRow,
    args: { workflow: SAMPLE_WORKFLOWS.deploy, now: SAMPLE_WORKFLOWS_NOW, gitRef: MAIN },
    // As wide as the list of the design's screens.
    decorators: [
        story => {
            const Story = story();
            return defineComponent({
                setup: () => () => h('div', { style: { width: '960px' } }, [h(Story)]),
            });
        },
    ],
} satisfies Meta<typeof WorkflowRow>;

export default meta;

type Story = StoryObj<typeof meta>;

/** Broke 3 hours ago: bright red, "Broken for 3h". */
export const BrokenNew: Story = {};

/** Broken on the tags `v*` for 4 days: quiet red. */
export const BrokenOld: Story = { args: { workflow: SAMPLE_WORKFLOWS.release, gitRef: TAGS } };

/** Failing for longer than the runs githq has go back ("4+ days"), with a run going. */
export const RunningAfterFailures: Story = { args: { workflow: SAMPLE_WORKFLOWS.nightly } };

/** Passing, with a run going. */
export const Passing: Story = { args: { workflow: SAMPLE_WORKFLOWS.probe } };

/** Passing, one run cancelled. */
export const Cancelled: Story = { args: { workflow: SAMPLE_WORKFLOWS.test } };

/** Two runs known. */
export const FewerRuns: Story = { args: { workflow: SAMPLE_WORKFLOWS.lint } };

/** Generated by GitHub, broken for weeks. */
export const ByGitHub: Story = { args: { workflow: SAMPLE_WORKFLOWS.dependabot } };

/** Disabled on GitHub: grey, never counts. */
export const Disabled: Story = { args: { workflow: SAMPLE_WORKFLOWS.backup } };

/** No run known yet. */
export const NoRuns: Story = { args: { workflow: SAMPLE_WORKFLOWS.codeql } };

/** The row the list's selection is on. */
export const Selected: Story = { args: { selected: true } };

/** On the cross-repository screen: the repository named, broken on two more patterns. */
export const WithRepository: Story = { args: { repository: 'fitloop/webapp', moreRefCount: 2 } };

/** W2: everything broken across repositories — every row's strip in one column. */
export const CrossRepository: Story = {
    render: () => ({
        setup: () => () =>
            h('div', [
                h(WorkflowRow, {
                    workflow: SAMPLE_WORKFLOWS.deploy,
                    now: SAMPLE_WORKFLOWS_NOW,
                    gitRef: MAIN,
                    repository: 'fitloop/webapp',
                    selected: true,
                }),
                h(WorkflowRow, {
                    workflow: SAMPLE_WORKFLOWS.release,
                    now: SAMPLE_WORKFLOWS_NOW,
                    gitRef: TAGS,
                    moreRefCount: 2,
                    repository: 'fitloop/webapp',
                }),
                h(WorkflowRow, {
                    workflow: SAMPLE_WORKFLOWS.nightly,
                    now: SAMPLE_WORKFLOWS_NOW,
                    gitRef: MAIN,
                    repository: 'mlaine/mdlint',
                }),
                h(WorkflowRow, {
                    workflow: SAMPLE_WORKFLOWS.dependabot,
                    now: SAMPLE_WORKFLOWS_NOW,
                    gitRef: MAIN,
                    repository: 'fitloop/api',
                }),
            ]),
    }),
};

/** W3a: a repository's own tab — no repository column, passing and disabled workflows too. */
export const RepositoryTab: Story = {
    render: () => ({
        setup: () => () =>
            h(
                'div',
                [
                    SAMPLE_WORKFLOWS.deploy,
                    SAMPLE_WORKFLOWS.release,
                    SAMPLE_WORKFLOWS.probe,
                    SAMPLE_WORKFLOWS.test,
                    SAMPLE_WORKFLOWS.dependabot,
                    SAMPLE_WORKFLOWS.lint,
                    SAMPLE_WORKFLOWS.backup,
                    SAMPLE_WORKFLOWS.codeql,
                ].map(workflow =>
                    h(WorkflowRow, {
                        key: workflow.workflow.id,
                        workflow,
                        now: SAMPLE_WORKFLOWS_NOW,
                        gitRef: workflow === SAMPLE_WORKFLOWS.release ? TAGS : MAIN,
                    }),
                ),
            ),
    }),
};
