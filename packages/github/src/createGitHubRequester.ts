import { isPlainObject } from '@nzyme/utils/isPlainObject.js';

import type { getSdk, Requester } from './generated.gen.js';
import { GITHUB_GRAPHQL_URL } from './GitHubApi.js';
import { GitHubApiError } from './GitHubApiError.js';
import type { GitHubGraphQLErrorEntry } from './GitHubApiError.js';
import { sendGitHubRequest } from './sendGitHubRequest.js';
import type { GitHubRequesterOptions } from './sendGitHubRequest.js';
import { readGitHubErrors } from './utils/readGitHubErrors.js';

/** What one call of the SDK may add: `sdk.ItemsByIds(variables, { onPartialErrors })`. */
export interface GitHubGraphQLCallOptions {
    /**
     * Takes a query's partial answer instead of throwing: GitHub answers a node that is gone or hidden, or a
     * nested field the token may not read, with `null` there and an `errors` entry pointing at it, next to the
     * rest of the data. When every error has such a `path`, they go here and the data is returned. An error
     * without a path, an answer without data, and any error of a mutation still throw — a write that reported
     * an error is treated as not done.
     */
    readonly onPartialErrors?: (errors: readonly GitHubGraphQLErrorEntry[]) => void;
}

/** The generated SDK over {@link createGitHubRequester}, which takes {@link GitHubGraphQLCallOptions} per call. */
export type GitHubSdk = ReturnType<typeof getSdk<GitHubGraphQLCallOptions>>;

/**
 * Builds the requester the SDK generated by `@graphql-codegen/typescript-generic-sdk` calls:
 * `getSdk(createGitHubRequester({ getToken }))`. Posts each operation to GitHub's GraphQL endpoint with the
 * user's token and throws {@link GitHubApiError} on a non-2xx answer or a non-empty `errors` array — unless the
 * call takes partial answers ({@link GitHubGraphQLCallOptions.onPartialErrors}).
 * @__NO_SIDE_EFFECTS__
 */
export function createGitHubRequester(options: GitHubRequesterOptions): Requester<GitHubGraphQLCallOptions> {
    return async function request<R, V>(doc: string, variables?: V, call?: GitHubGraphQLCallOptions): Promise<R> {
        const answer = await sendGitHubRequest(options, {
            url: GITHUB_GRAPHQL_URL,
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            // The generated SDK passes a `TypedDocumentString`, a `String` object, which serializes as its text.
            body: JSON.stringify({ query: doc, variables: variables ?? {} }),
        });

        const { status, payload, retryAfter } = answer;
        const data = isPlainObject(payload) && isPlainObject(payload.data) ? payload.data : null;
        const errors = readGitHubErrors(payload);
        if (errors.length > 0) {
            const onPartialErrors = call?.onPartialErrors;
            const partial = onPartialErrors !== undefined && data !== null && !isMutation(doc) && errors.every(hasPath);
            if (!partial) {
                const summary = errors.map(error => (error.type ? `${error.type}: ${error.message}` : error.message));
                const message = `GitHub GraphQL error: ${summary.join('; ')}`;
                throw new GitHubApiError({ status, message, errors, retryAfter });
            }

            onPartialErrors(errors);
        }

        if (data === null) {
            throw new GitHubApiError({ status, message: 'GitHub GraphQL answer has no data', retryAfter });
        }

        // The generated SDK pairs every document with its result type, and GitHub validates the document
        // against the schema the types were generated from, so `data` has the shape of `R`.
        return data as R;
    };
}

/** The generated documents start with their operation; fragments follow it. */
function isMutation(query: string) {
    return /^\s*mutation\b/.test(query);
}

function hasPath(error: GitHubGraphQLErrorEntry) {
    return error.path !== undefined && error.path.length > 0;
}
